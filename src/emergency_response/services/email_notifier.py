
import logging
import os
import smtplib
from email.message import EmailMessage
from pathlib import Path

from dotenv import load_dotenv

logger = logging.getLogger(__name__)

# Load the project-root .env regardless of the terminal's working directory.
PROJECT_ROOT = Path(__file__).resolve().parents[3]
load_dotenv(PROJECT_ROOT / ".env")


def email_is_configured() -> bool:
    """Check whether all required SMTP settings are present."""
    required = (
        "SMTP_HOST",
        "SMTP_PORT",
        "SMTP_USERNAME",
        "SMTP_PASSWORD",
        "EMAIL_FROM",
        "EMAIL_TO",
    )
    return all(os.getenv(key, "").strip() for key in required)


def send_emergency_notification(report: dict) -> str:
    """Email the configured authority without interrupting report creation."""
    if not email_is_configured():
        logger.warning("Emergency email not sent: SMTP settings are incomplete.")
        return "not_configured"

    try:
        message = EmailMessage()
        message["Subject"] = (
            f"[ResQAI MOCK ALERT] Emergency {report.get('report_id', 'Unknown')}"
        )
        message["From"] = os.environ["EMAIL_FROM"]
        message["To"] = [
            address.strip()
            for address in os.environ["EMAIL_TO"].split(",")
            if address.strip()
        ]

        message.set_content(
            "ResQAI Emergency Notification — MOCK PRACTICE\n\n"
            f"Report ID: {report.get('report_id', 'Unknown')}\n"
            f"Emergency type: {report.get('emergency_type', 'Unknown')}\n"
            f"Location ID: {report.get('location_id', 'Unknown')}\n"
            f"Priority: {report.get('priority', 'Unknown')}\n"
            f"People affected: {report.get('people_affected', 'Unknown')}\n"
            f"Status: {report.get('status', 'Unknown')}\n\n"
            f"Description:\n{report.get('description', 'No description')}\n\n"
            "This is an automatically generated student-project test alert. "
            "It is not a verified real-world emergency dispatch."
        )

        with smtplib.SMTP(
            os.environ["SMTP_HOST"],
            int(os.environ["SMTP_PORT"]),
            timeout=15,
        ) as server:
            server.starttls()
            server.login(
                os.environ["SMTP_USERNAME"],
                os.environ["SMTP_PASSWORD"],
            )
            server.send_message(message)

        logger.info("Emergency notification email sent for %s", report.get("report_id"))
        return "sent"

    except Exception:
        # Do not log credentials or SMTP authentication details.
        logger.exception(
            "Emergency notification email failed for %s",
            report.get("report_id"),
        )
        return "failed"

