            f"Additional ambulances requested: {request['ambulance_count']}\n"
            f"Reason: {request['reason']}\n"
            f"Submitted at: {request['created_at']}\n\n"
            "This is a request generated by a student project. "
            "It is not an official dispatch order or confirmation that "
