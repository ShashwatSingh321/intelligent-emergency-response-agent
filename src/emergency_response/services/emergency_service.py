from dataclasses import dataclass
from math import inf

from emergency_response.agents.decision_engine import (
    calculate_priority,
    explain_priority,
)
from emergency_response.models.ambulance import Ambulance
from emergency_response.models.emergency import EmergencyReport
from emergency_response.routing.graph import CampusGraph
from emergency_response.services.dispatch_service import (
    select_ambulance_by_route,
)

import os
import smtplib
import logging
from email.message import EmailMessage

logger = logging.getLogger(__name__)


@dataclass
class EmergencyProcessingResult:
    """Structured result of preliminary emergency processing."""

    report_id: str
    priority: int
    priority_explanation: str
    ambulance: Ambulance | None
    route: list[str]
    route_cost: float
    recommendation: str

    @property
    def ambulance_found(self) -> bool:
        return self.ambulance is not None

    @property
    def route_found(self) -> bool:
        return bool(self.route) and self.route_cost != inf


def process_emergency(
    report: EmergencyReport,
    ambulances: list[Ambulance],
    graph: CampusGraph,
    required_equipment: set[str] | None = None,
) -> EmergencyProcessingResult:
    """
    Assess an emergency and recommend a suitable ambulance and route.

    This function produces a recommendation only. It does not dispatch
    a real vehicle or change the report's status.
    """

    priority = calculate_priority(report)
    priority_explanation = explain_priority(report)

    ambulance, route, route_cost = select_ambulance_by_route(
        report=report,
        ambulances=ambulances,
        graph=graph,
        required_equipment=required_equipment,
    )

    if ambulance is None:
        recommendation = (
            "No suitable reachable ambulance was found. "
            "Escalate for human review and alternative arrangements."
        )
    else:
        recommendation = (
            f"Ambulance {ambulance.id} is recommended for human review. "
            f"Estimated route cost: {route_cost}."
        )

    return EmergencyProcessingResult(
        report_id=report.id,
        priority=priority,
        priority_explanation=priority_explanation,
        ambulance=ambulance,
        route=route,
        route_cost=route_cost,
        recommendation=recommendation,
    )


def email_is_configured() -> bool:
    """Return True if all required SMTP environment variables are set."""
    required = [
        "EMAIL_FROM",
        "EMAIL_TO",
        "SMTP_HOST",
        "SMTP_PORT",
        "SMTP_USERNAME",
        "SMTP_PASSWORD",
    ]
    return all(os.environ.get(key) for key in required)


def send_ambulance_request_notification(request: dict) -> str:
    """Notify the configured recipient about an additional ambulance request."""
    if not email_is_configured():
        logger.warning("Ambulance request email not sent: SMTP is not configured.")
        return "not_configured"

    try:
        message = EmailMessage()
        message["Subject"] = (
            f"[ResQAI MOCK REQUEST] {request['request_id']} — "
            f"Additional ambulances requested"
        )
        message["From"] = os.environ["EMAIL_FROM"]
        message["To"] = [
            address.strip()
            for address in os.environ["EMAIL_TO"].split(",")
            if address.strip()
        ]

        message.set_content(
            "ResQAI — Additional Ambulance Request (Student Project)\n\n"
            f"Request ID: {request['request_id']}\n"
            f"Campus location: {request['location_name']}\n"
            f"Location ID: {request['location_id']}\n"
            f"Additional ambulances requested: {request['ambulance_count']}\n"
            f"Reason: {request['reason']}\n"
            f"Submitted at: {request['created_at']}\n\n"
            "This is a request generated by a student project. "
            "It is not an official dispatch order or confirmation that "
            "any ambulance has been assigned or dispatched."
        )

        with smtplib.SMTP(
            os.environ["SMTP_HOST"],
            int(os.environ["SMTP_PORT"]),
            timeout=15,
        ) as server:
            server.starttls()
            server.login(
                os.environ["SMTP_USERNAME"],
                os.environ["SMTP_PASSWORD"],
            )
            server.send_message(message)

        logger.info(
            "Ambulance request email sent for %s",
            request["request_id"],
        )
        return "sent"

    except Exception:
        logger.exception(
            "Ambulance request email failed for %s",
            request.get("request_id", "Unknown"),
        )
        return "failed"